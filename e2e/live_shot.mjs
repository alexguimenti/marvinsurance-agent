import { createRequire } from 'node:module'
const require = createRequire(import.meta.url)
const { chromium } = require('@playwright/test')
const [path, out, theme = 'light'] = process.argv.slice(2)
const browser = await chromium.launch()
const page = await browser.newPage({ viewport: { width: 1280, height: 800 } })
await page.addInitScript((t) => localStorage.setItem('marvin-theme', t), theme)
await page.goto('http://127.0.0.1:5173/')
await page.getByLabel('Email').fill('dana.whitfield@marvinsurance.example')
await page.getByLabel('Password').fill(process.env.HANDLER_PASSWORD)
await page.getByRole('button', { name: 'Sign in' }).click()
await page.getByRole('button', { name: 'Sign out' }).waitFor()
await page.goto('http://127.0.0.1:5173' + path)
await page.waitForTimeout(3500)
await page.screenshot({ path: out })
await browser.close()
