"""Make the runtime/pyproject.toml the AgentCore CLI asks for before it deploys.

The CLI refuses to deploy a Python runtime whose folder has no pyproject.toml. Here the project's packages are the `runtime`
group of backend/pyproject.toml, so this script writes runtime/pyproject.toml from that group at the versions backend/uv.lock
holds. It is generated: git ignores it. The real package is staged by agentcore/cdk/lib/cdk-stack.ts during `agentcore deploy`,
which copies runtime/ and backend/agent and lists the same packages.

    python scripts/prepare_runtime.py   (any Python 3.10 or newer: it uses only the standard library, and uv)
"""

import json
import shutil
import subprocess
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
RUNTIME = REPO / "runtime"
PYTHON = "3.12"  # runtimeVersion PYTHON_3_12 in agentcore/agentcore.json


def uv() -> str:
    """uv's path: the kernel's or terminal's PATH, or the installer's own folder."""
    return shutil.which("uv") or str(Path.home() / ".local" / "bin" / "uv.exe")


def pinned_packages() -> list[str]:
    """The `runtime` group's packages, each at the version backend/uv.lock holds."""
    command = [uv(), "export", "--project", "backend", "--only-group", "runtime", "--no-hashes", "--no-annotate", "--no-emit-project", "--quiet"]
    exported = subprocess.run(command, cwd=REPO, check=True, capture_output=True, text=True).stdout
    packages = [line.strip() for line in exported.splitlines() if line.strip() and not line.startswith("#")]
    assert packages and all("==" in package for package in packages), "uv export gave no pinned packages"
    return packages


def write_pyproject(packages: list[str]) -> None:
    """runtime/pyproject.toml, for the CLI to install from."""
    listed = "".join(f"    {json.dumps(package)},\n" for package in packages)  # a marker holds single quotes: JSON's double quotes are TOML's
    text = f"""# Generated by scripts/prepare_runtime.py from backend/pyproject.toml's `runtime` group at backend/uv.lock's versions: do not edit.
[project]
name = "undercover-runtime"
version = "0.1.0"
requires-python = ">={PYTHON}"
dependencies = [
{listed}]
"""
    (RUNTIME / "pyproject.toml").write_text(text, encoding="utf-8")


def main() -> None:
    packages = pinned_packages()
    write_pyproject(packages)
    print(f"runtime/pyproject.toml: {len(packages)} packages at uv.lock's versions")
    print("Ready: run `agentcore deploy` from the root of the repo.")


if __name__ == "__main__":
    main()
